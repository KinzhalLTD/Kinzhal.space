// Builds the Netlify site from the single-file app (app/kinzhal-nest.html, the same file as the Claude artifact):
//   public/index.html  markup + styles (no inline scripts, so the Content-Security-Policy can forbid them)
//   public/app.js      the app script, switched to cloud mode (login, team, live data)
// Run: npm run build
import fs from 'node:fs';
const src = fs.readFileSync(new URL('../app/kinzhal-nest.html', import.meta.url), 'utf8');
const sOpen = src.indexOf('<script>'), sClose = src.lastIndexOf('</script>');
if (sOpen < 0 || sClose < 0) throw new Error('No <script> block found');
const before = src.slice(0, sOpen), script = src.slice(sOpen + 8, sClose);
const stEnd = before.indexOf('</style>') + 8;
const head = before.slice(0, stEnd), body = before.slice(stEnd);
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="robots" content="noindex,nofollow">
<meta name="referrer" content="strict-origin-when-cross-origin">
<meta name="theme-color" content="#07060c">
<link rel="shortcut icon" href="/favicon.ico?v=4">
<link rel="icon" href="/favicon-32.png?v=4" sizes="32x32" type="image/png">
<link rel="icon" href="/icon-512.png?v=4" sizes="512x512" type="image/png">
<link rel="apple-touch-icon" href="/apple-touch-icon.png?v=4">
<meta name="description" content="Kinzhal Nest — private HQ for Kinzhal LTD Co. games.">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Kinzhal Nest">
<meta property="og:title" content="Kinzhal Nest">
<meta property="og:description" content="Private HQ for Kinzhal LTD Co. games.">
<meta property="og:url" content="https://kinzhalnest.netlify.app/">
<meta property="og:image" content="https://kinzhalnest.netlify.app/og-image.jpg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:image" content="https://kinzhalnest.netlify.app/og-image.jpg">
${head.trim()}
</head>
<body>
${body.trim()}
<noscript><p style="padding:24px;color:#fff">Kinzhal Nest needs JavaScript.</p></noscript>
<script src="/app.js" defer></script>
<script type="module" src="/cloud.js"></script>
</body>
</html>
`;
fs.writeFileSync(new URL('../public/index.html', import.meta.url), html);
fs.writeFileSync(new URL('../public/app.js', import.meta.url), '// Kinzhal Nest — generated by scripts/build.js from app/kinzhal-nest.html. Edit the source file, not this one.\nwindow.KN_CLOUD = true;\n' + script.trim() + '\n');
console.log(`Built public/index.html (${(html.length / 1024).toFixed(0)} KB) and public/app.js (${(script.length / 1024).toFixed(0)} KB)`);
